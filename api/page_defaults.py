def merge_page_content(defaults, saved):
    """Fill missing keys from defaults. Saved lists replace the default list."""
    if saved is None:
        return defaults
    if isinstance(defaults, list):
        return saved if isinstance(saved, list) else defaults
    if not isinstance(defaults, dict):
        return defaults if saved is None else saved
    if not isinstance(saved, dict):
        return defaults
    merged = dict(defaults)
    for key, value in saved.items():
        if value is None:
            continue
        current = defaults.get(key)
        if isinstance(value, list):
            merged[key] = value
        elif isinstance(value, dict) and isinstance(current, dict):
            merged[key] = merge_page_content(current, value)
        else:
            merged[key] = value
    return merged
